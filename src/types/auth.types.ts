import type { z } from "zod";
import type { UserRole, YearOfStudy } from "../generated/prisma/enums.js";
import type { loginSchema, signInSchema } from "../schemas/auth.schema.js";

// ─── Request DTOs (inferred from the Zod schemas, so they can't drift apart) ───

export type SignInDto = z.infer<typeof signInSchema>;
export type LoginDto = z.infer<typeof loginSchema>;

// ─── Response DTOs ───

// The user as the client sees it: never includes passwordHash.
export interface AuthUserDto {
  id: string;
  name: string;
  email: string;
  role: UserRole;
  yearOfStudy: YearOfStudy | null;
}

// What the service hands the controller. The controller puts refreshToken in a
// cookie and the rest in the JSON body.
export interface AuthResult {
  user: AuthUserDto;
  accessToken: string;
  refreshToken: string;
}

export interface RefreshResult {
  accessToken: string;
  refreshToken: string;
}

// ─── Repository inputs / outputs ───

export interface NewStudent {
  name: string;
  email: string;
  passwordHash: string;
  yearOfStudy: YearOfStudy;
}

// The id is generated by us, not the database, because it is part of the refresh token.
export interface NewSession {
  id: string;
  userId: string;
  refreshTokenHash: string;
  expiresAt: Date;
}

export interface UserWithPassword {
  user: AuthUserDto;
  passwordHash: string;
}

export interface SessionRecord {
  id: string;
  userId: string;
  userRole: UserRole;
  refreshTokenHash: string;
  expiresAt: Date;
  revokedAt: Date | null;
}
